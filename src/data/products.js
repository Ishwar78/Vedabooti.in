export const productMap = allProducts.reduce((map, product) => {
    map[product.slug] = product;
    map[String(product.id)] = product;
    return map;
}, {});

export function getProductBySlug(slug) {
    if (!slug) return allProducts[0];
    return productMap[slug] || allProducts.find(p => p.slug === slug || String(p.id) === String(slug)) || allProducts[0];
}
